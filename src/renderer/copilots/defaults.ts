export function seedDefaultCopilots(current: CopilotDetail[], now = Date.now()): CopilotDetail[] {
  const existingIds = new Set(current.map((copilot) => copilot.id))
  const missingDefaults = DEFAULT_COPILOTS.filter((copilot) => !existingIds.has(copilot.id)).map((copilot) => ({
    ...copilot,
    createdAt: copilot.createdAt ?? now,
    updatedAt: now,
  }))
  return [...missingDefaults, ...current]
}
